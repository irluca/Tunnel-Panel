func TestGenerateEzKeyRoundTrip(t *testing.T) {
	for i := 0; i < 20; i++ {
		key, err := GenerateEzKey()
		if err != nil {
			t.Fatal(err)
		}
		if len(key) != 29 {
			t.Fatalf("generated key %q is %d characters, want 29", key, len(key))
		}
		parsed, err := ParseEzKey(key)
		if err != nil {
			t.Fatalf("ParseEzKey(%q) = %v", key, err)
		}
		if parsed != key {
			t.Fatalf("ParseEzKey(%q) = %q", key, parsed)
		}
	}
}

func TestParseEzKeyAcceptsTheRealBinaryKey(t *testing.T) {
	// This key was generated by the real eztunnel binary (`eztunnel key`),
	// so accepting it proves the panel's check-symbol math matches the
	// binary's own.
	key := "vaqj6-sj2s9-12t8p-angnr-tr232"
	parsed, err := ParseEzKey(key)
	if err != nil {
		t.Fatalf("ParseEzKey(%q) = %v", key, err)
	}
	if parsed != key {
		t.Fatalf("ParseEzKey(%q) = %q", key, parsed)
	}
	// Case, dashes and spaces are ignored; o reads as 0, i/l as 1.
	loose := "VAQJ6 SJ2S9 12T8P ANGNR TR232"
	parsed, err = ParseEzKey(loose)
	if err != nil || parsed != key {
		t.Fatalf("ParseEzKey(%q) = %q, %v", loose, parsed, err)
	}
}

func TestParseEzKeyRefusesBadKeys(t *testing.T) {
	for _, bad := range []string{
		"vaqj6-sj2s9-12t8p-angnr-tr233", // wrong check symbol
		"vaqj6-sj2s9-12t8p-angnr-tr23",  // too short
		"vaqj6-sj2s9-12t8p-angnr-tr232x", // too long
		"vaqj6-sj2s9-12t8p-angnr-tr23u", // u is not in the alphabet
		"vaqj6-sj2s9-12t8p-angnr-tr23!", // punctuation is not in the alphabet
	} {
		if _, err := ParseEzKey(bad); err == nil {
			t.Fatalf("ParseEzKey(%q) accepted a bad key", bad)
		}
	}
}

func TestEzTransports(t *testing.T) {
	if len(EzTransports) != 15 {
		t.Fatalf("EzTransports has %d entries, want 15", len(EzTransports))
	}
	for _, tr := range EzTransports {
		if !EzTransportValid(tr) {
			t.Fatalf("EzTransportValid(%q) = false", tr)
		}
	}
	if EzTransportValid("gre") || EzTransportValid("esp") {
		t.Fatal("GRE and ESP are not EZTunnel transports")
	}
	if !EzTransportNeedsTLS(EzTransportWSS) || EzTransportNeedsTLS(EzTransportTCP) {
		t.Fatal("TLS carriers are https, wss and xhttps only")
	}
	if !EzTransportNeedsRaw(EzTransportMirage) || !EzTransportNeedsRaw(EzTransportFECRaw) {
		t.Fatal("mirage and fec-raw are raw carriers")
	}
	if EzTransportNeedsRaw(EzTransportFECUDP) {
		t.Fatal("fec-udp is not a raw carrier")
	}
	if !EzTransportIsMirage(EzTransportMirage) || EzTransportIsMirage(EzTransportTUN) {
		t.Fatal("only mirage is the Mirage transport")
	}
	if _, ok := EzBinaryURL("amd64"); !ok {
		t.Fatal("no binary URL for amd64")
	}
	if _, ok := EzBinaryURL("arm64"); !ok {
		t.Fatal("no binary URL for arm64")
	}
	if _, ok := EzBinaryURL("386"); ok {
		t.Fatal("a binary URL exists for an architecture the release does not ship")
	}
}

func ezSpec(transport, mode string) TunnelSpec {
	return TunnelSpec{
		Name: "eztunnel-a-1", Kind: KindEZTunnel,
		Local: "203.0.113.10", Remote: "198.51.100.20",
		Mtu: 1400, EzMode: mode, EzTransport: transport,
		EzKey: "vaqj6-sj2s9-12t8p-angnr-tr232", EzPort: 8443,
	}
}

func ezAddrs() []Address {
	return []Address{{Address: "10.77.0.1", Peer: "10.77.0.2"}}
}

func decodeEzConfig(t *testing.T, b []byte) map[string]any {
	t.Helper()
	var m map[string]any
	if err := json.Unmarshal(b, &m); err != nil {
		t.Fatalf("rendered config is not JSON: %v\n%s", err, b)
	}
	return m
}

func TestEzConfigJSONTCP(t *testing.T) {
	spec := ezSpec(EzTransportTCP, EzModeServer)
	b, err := EzConfigJSON(spec, ezAddrs())
	if err != nil {
		t.Fatal(err)
	}
	m := decodeEzConfig(t, b)
	if m["mode"] != "server" || m["tunnel_key"] != spec.EzKey {
		t.Fatalf("server config = %s", b)
	}
	listeners := m["listeners"].([]any)
	entry := listeners[0].(map[string]any)
	if entry["addr"] != "0.0.0.0:8443" || entry["transport"] != "tcp" {
		t.Fatalf("server listener = %v", entry)
	}
	if _, ok := entry["tls_auto"]; ok {
		t.Fatal("tcp must not carry tls_auto")
	}
	tun := m["tun"].(map[string]any)
	if tun["name"] != "eztunnel-a-1" || tun["address"] != "10.77.0.1" || tun["peer_address"] != "10.77.0.2" {
		t.Fatalf("tun block = %v", tun)
	}

	client := ezSpec(EzTransportTCP, EzModeClient)
	b, err = EzConfigJSON(client, []Address{{Address: "10.77.0.2", Peer: "10.77.0.1"}})
	if err != nil {
		t.Fatal(err)
	}
	m = decodeEzConfig(t, b)
	paths := m["paths"].([]any)
	entry = paths[0].(map[string]any)
	if entry["addr"] != "198.51.100.20:8443" {
		t.Fatalf("client path addr = %v", entry["addr"])
	}
	if entry["connection_pool"] != float64(1) {
		t.Fatalf("client connection_pool = %v", entry["connection_pool"])
	}
	if _, ok := m["listeners"]; ok {
		t.Fatal("client config must not carry listeners")
	}
}

func TestEzConfigJSONWSSAndXHTTPS(t *testing.T) {
	spec := ezSpec(EzTransportWSS, EzModeServer)
	b, err := EzConfigJSON(spec, ezAddrs())
	if err != nil {
		t.Fatal(err)
	}
	m := decodeEzConfig(t, b)
	entry := m["listeners"].([]any)[0].(map[string]any)
	if entry["tls_auto"] != true {
		t.Fatalf("wss must carry tls_auto: %v", entry)
	}
	if entry["http_path"] != "/tunnel" {
		t.Fatalf("wss http_path = %v", entry["http_path"])
	}

	spec = ezSpec(EzTransportXHTTPS, EzModeServer)
	spec.EzXhttpMode = "packet-up"
	spec.EzXhttpHost = "tunnel.example.com"
	b, err = EzConfigJSON(spec, ezAddrs())
	if err != nil {
		t.Fatal(err)
	}
	m = decodeEzConfig(t, b)
	entry = m["listeners"].([]any)[0].(map[string]any)
	if entry["tls_auto"] != true {
		t.Fatal("xhttps must carry tls_auto")
	}
	xhttp := entry["xhttp"].(map[string]any)
	if xhttp["mode"] != "packet-up" || xhttp["host"] != "tunnel.example.com" {
		t.Fatalf("xhttp block = %v", xhttp)
	}
}

func TestEzConfigJSONFECUDPAndMirage(t *testing.T) {
	spec := ezSpec(EzTransportFECUDP, EzModeServer)
	spec.EzPort = 7000
	b, err := EzConfigJSON(spec, ezAddrs())
	if err != nil {
		t.Fatal(err)
	}
	m := decodeEzConfig(t, b)
	entry := m["listeners"].([]any)[0].(map[string]any)
	fec := entry["fec"].(map[string]any)
	if fec["mtu"] != float64(1350) || fec["knock"] != true {
		t.Fatalf("fec block = %v", fec)
	}
	if _, ok := entry["raw"]; ok {
		t.Fatal("fec-udp must not carry a raw block")
	}

	spec = ezSpec(EzTransportMirage, EzModeServer)
	spec.EzPort = 443
	spec.EzRawProfile = "udp"
	spec.EzRawInterface = "eth0"
	spec.EzMirageUplink = "udp"
	spec.EzMirageDownlink = "icmp"
	spec.EzSpoofSources = []string{"203.0.113.30"}
	spec.EzMirageExpected = []string{"203.0.113.30"}
	b, err = EzConfigJSON(spec, ezAddrs())
	if err != nil {
		t.Fatal(err)
	}
	m = decodeEzConfig(t, b)
	entry = m["listeners"].([]any)[0].(map[string]any)
	if entry["addr"] != "203.0.113.10:443" {
		t.Fatalf("mirage listener addr = %v", entry["addr"])
	}
	raw := entry["raw"].(map[string]any)
	if raw["profile"] != "udp" || raw["peer_ip"] != "198.51.100.20" || raw["l4_port"] != float64(443) {
		t.Fatalf("raw block = %v", raw)
	}
	if raw["mirage_acknowledgement"] != "experimental-v2" {
		t.Fatalf("mirage acknowledgement = %v", raw["mirage_acknowledgement"])
	}
	mirage := raw["mirage"].(map[string]any)
	if mirage["uplink"] != "udp" || mirage["downlink"] != "icmp" {
		t.Fatalf("mirage block = %v", mirage)
	}
	pool := mirage["source_pool"].([]any)
	if len(pool) != 1 || pool[0] != "203.0.113.30" {
		t.Fatalf("mirage source_pool = %v", pool)
	}
}

