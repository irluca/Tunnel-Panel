// TestEzConfigJSONPassesTheRealBinary renders the panel's configs for the
// transports that need the most care and checks them with the real eztunnel
// binary's own --check. It only runs when EZ_BINARY points at an eztunnel
// binary (the release binary), so the suite does not depend on it.
func TestParseEzConfigRoundTrip(t *testing.T) {
	spec := ezSpec(EzTransportMirage, EzModeServer)
	spec.EzPort = 443
	spec.EzRawProfile = "udp"
	spec.EzRawInterface = "eth0"
	spec.EzMirageUplink = "udp"
	spec.EzMirageDownlink = "icmp"
	spec.EzSpoofSources = []string{"203.0.113.7", "198.51.100.23"}
	spec.EzMirageExpected = []string{"203.0.113.7"}
	raw, err := EzConfigJSON(spec, []Address{{Address: "172.17.1.1", Peer: "172.17.1.2"}})
	if err != nil {
		t.Fatalf("rendering failed: %v", err)
	}
	cfg, err := ParseEzConfig(raw)
	if err != nil {
		t.Fatalf("parsing the rendered config failed: %v", err)
	}
	if cfg.Mode != EzModeServer || cfg.Transport != "mirage" || cfg.Port != 443 {
		t.Fatalf("the parsed config is not the server mirage tunnel on 443: %+v", cfg)
	}
	if cfg.Key != spec.EzKey {
		t.Fatal("the parsed key differs from the rendered one")
	}
	if cfg.RawProfile != "udp" || cfg.RawInterface != "eth0" {
		t.Fatalf("the raw block did not survive: %+v", cfg)
	}
	if cfg.MirageUplink != "udp" || cfg.MirageDownlink != "icmp" {
		t.Fatalf("the Mirage profiles did not survive: %+v", cfg)
	}
	if len(cfg.SpoofSources) != 2 || cfg.SpoofSources[1] != "198.51.100.23" {
		t.Fatalf("the spoof sources did not survive: %v", cfg.SpoofSources)
	}
	if len(cfg.MirageExpected) != 1 || cfg.MirageExpected[0] != "203.0.113.7" {
		t.Fatalf("the expected sources did not survive: %v", cfg.MirageExpected)
	}
	// A raw carrier names both underlay endpoints in its raw block.
	if cfg.LocalEndpoint != spec.Local || cfg.RemoteEndpoint != spec.Remote {
		t.Fatalf("the endpoints did not survive: %q, %q", cfg.LocalEndpoint, cfg.RemoteEndpoint)
	}
	if cfg.TunName != spec.Name || cfg.TunMtu != spec.Mtu {
		t.Fatalf("the TUN block did not survive: %+v", cfg)
	}

	// A server TCP config names neither endpoint: the parse succeeds and
	// the endpoints stay empty rather than invented.
	tcp, err := EzConfigJSON(ezSpec(EzTransportTCP, EzModeServer), []Address{{Address: "172.17.1.1", Peer: "172.17.1.2"}})
	if err != nil {
		t.Fatalf("rendering the TCP config failed: %v", err)
	}
	parsed, err := ParseEzConfig(tcp)
	if err != nil {
		t.Fatalf("parsing the TCP config failed: %v", err)
	}
	if parsed.LocalEndpoint != "" || parsed.RemoteEndpoint != "" {
		t.Fatalf("a server TCP config names endpoints it does not have: %q, %q", parsed.LocalEndpoint, parsed.RemoteEndpoint)
	}

	// A config with a key that does not parse is not trusted at all.
	bad := map[string]any{"mode": "server", "tunnel_key": "not-a-key", "listeners": []map[string]any{{"addr": "0.0.0.0:8443", "transport": "tcp"}}}
	encoded, _ := json.Marshal(bad)
	if _, err := ParseEzConfig(encoded); err == nil {
		t.Fatal("a config with an unparsable key was accepted")
	}
	// A config naming an unknown transport is not trusted either.
	bad["tunnel_key"] = spec.EzKey
	bad["listeners"] = []map[string]any{{"addr": "0.0.0.0:8443", "transport": "teleport"}}
	encoded, _ = json.Marshal(bad)
	if _, err := ParseEzConfig(encoded); err == nil {
		t.Fatal("a config with an unknown transport was accepted")
	}
}

func TestEzConfigJSONPassesTheRealBinary(t *testing.T) {
	bin := os.Getenv("EZ_BINARY")
	if bin == "" {
		t.Skip("EZ_BINARY is not set")
	}
	cases := map[string]TunnelSpec{
		"tcp-server":     ezSpec(EzTransportTCP, EzModeServer),
		"tcp-client":     ezSpec(EzTransportTCP, EzModeClient),
		"wss-server":     ezSpec(EzTransportWSS, EzModeServer),
		"xhttps-server":  ezSpec(EzTransportXHTTPS, EzModeServer),
		"fecudp-server":  ezSpec(EzTransportFECUDP, EzModeServer),
		"mirage-server":  ezSpec(EzTransportMirage, EzModeServer),
		"mirage-client":  ezSpec(EzTransportMirage, EzModeClient),
		"fecraw-server":  ezSpec(EzTransportFECRaw, EzModeServer),
		"tunraw-server":  ezSpec(EzTransportTUN, EzModeServer),
		"parallax-server": ezSpec(EzTransportParallax, EzModeServer),
	}
	xhttp := cases["xhttps-server"]
	xhttp.EzXhttpMode = "packet-up"
	xhttp.EzXhttpHost = "tunnel.example.com"
	cases["xhttps-server"] = xhttp
	fecudp := cases["fecudp-server"]
	fecudp.EzPort = 7000
	cases["fecudp-server"] = fecudp
	for _, name := range []string{"mirage-server", "mirage-client"} {
		c := cases[name]
		c.EzPort = 443
		c.EzRawProfile = "udp"
		c.EzRawInterface = "eth0"
		c.EzMirageUplink = "udp"
		c.EzMirageDownlink = "icmp"
		c.EzSpoofSources = []string{"203.0.113.30"}
		c.EzMirageExpected = []string{"203.0.113.30"}
		cases[name] = c
	}
	for _, name := range []string{"fecraw-server", "tunraw-server"} {
		c := cases[name]
		c.EzPort = 443
		c.EzRawProfile = "tcp"
		c.EzRawInterface = "eth0"
		cases[name] = c
	}
	dir := t.TempDir()
	for name, spec := range cases {
		addrs := ezAddrs()
		if strings.HasSuffix(name, "client") {
			addrs = []Address{{Address: "10.77.0.2", Peer: "10.77.0.1"}}
		}
		b, err := EzConfigJSON(spec, addrs)
		if err != nil {
			t.Fatalf("%s: %v", name, err)
		}
		path := filepath.Join(dir, name+".json")
		if err := os.WriteFile(path, b, 0o600); err != nil {
			t.Fatal(err)
		}
		cmd := exec.Command(bin, "--config", path, "--check")
		out, err := cmd.CombinedOutput()
		if err != nil {
			t.Fatalf("%s: the real binary refused the panel's config: %v\n%s\n%s", name, err, out, b)
		}
	}
}
